import { mount, flushPromises } from '@vue/test-utils'
import ProductsView from '../../../src/views/ProductsView.vue'
import CarriersView from '../../../src/views/CarriersView.vue'
import UsersView from '../../../src/views/UsersView.vue'
import ModalHost from '../../../src/components/ModalHost.vue'
import { db, resetDb } from '../../../src/stores/db'
import { loginAs, logout } from '../../../src/stores/session'
import { createSession } from '../../../src/factories/sessionFactory'
import { toasts, closeModal, modal } from '../../../src/stores/ui'
import { api, ok, err } from '../../helpers/fakeApi'
import { meAdmin, meSeller, domains, product, carrier } from '../../helpers/fixtures'

vi.mock('../../../src/services/http', async () => (await import('../../helpers/fakeApi.js')).fakeHttpModule())

beforeEach(async () => {
  api.reset()
  api.on('POST /auth/logout', ok(null, {}, 204))
  api.on('GET /dominios', ok(domains))
  resetDb()
  await logout()
  toasts.splice(0)
  closeModal()
  loginAs(createSession(meAdmin))
})

const mountView = async (View) => {
  const w = mount(View, { global: { stubs: { teleport: true } } })
  await flushPromises()
  return w
}
const lastToast = () => toasts.at(-1).parts.map((p) => p.text).join('')

describe('ProductsView', () => {
  const list = () => [product(), product({ id: 'p-hcl', nome: 'HCL', densidade: null, embalagens: ['GRANEL_LIQUIDO'], ativo: false, versao: 2 })]

  it('lista da API com embalagens por descrição, densidade e situação', async () => {
    api.on('GET /produtos', ok(list()))
    const w = await mountView(ProductsView)
    const rows = w.findAll('tbody tr')
    expect(rows).toHaveLength(2)
    expect(rows[0].text()).toContain('SODA CÁUSTICA')
    expect(rows[0].text()).toContain('1,520 g/cm³')
    expect(rows[0].findAll('.pill.st-tra').map((p) => p.text())).toEqual(['Big bag', 'Granel líquido'])
    expect(rows[0].text()).toContain('ATIVO')
    expect(rows[1].classes()).toContain('off')
    expect(rows[1].text()).toContain('INATIVO')
    expect(w.find('.card-h .cnt').text()).toBe('2 itens')
  })
  it('incluir produto: chips vêm de /dominios, POST com nome em maiúsculas', async () => {
    api.on('GET /produtos', ok([]))
    api.on('POST /produtos', ({ body }) => ok(product({ id: 'p-new', ...body }), {}, 201))
    const w = await mountView(ProductsView)
    await w.find('[data-act="new-product"]').trigger('click')
    expect(w.findAll('.chipz label').map((l) => l.text())).toEqual(['Big bag', 'Granel líquido', 'Bombona'])
    await w.find('#pr-name').setValue('hcl')
    await w.find('#pr-dens').setValue('1,19')
    await w.findAll('.chipz input')[1].setValue(true)
    await w.find('[data-act="save-product"]').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/produtos')[0].body).toEqual({ nome: 'HCL', descricao: null, onu: null, risco: null, densidade: '1.19', embalagens: ['GRANEL_LIQUIDO'], fatores: {} })
    expect(w.findAll('tbody tr')).toHaveLength(1)
    expect(lastToast()).toBe('Produto HCL incluído com sucesso.')
  })
  it('validação local: sem nome ou sem embalagem nem chama a API', async () => {
    api.on('GET /produtos', ok([]))
    const w = await mountView(ProductsView)
    await w.find('[data-act="new-product"]').trigger('click')
    await w.find('[data-act="save-product"]').trigger('click')
    await flushPromises()
    expect(toasts.at(-1).type).toBe('err')
    expect(api.called('POST', '/produtos')).toHaveLength(0)
  })
  it('editar envia PATCH com versao', async () => {
    api.on('GET /produtos', ok([product({ versao: 7 })]))
    api.on('PATCH /produtos/:id', ({ body }) => ok(product({ ...body, versao: 8 })))
    const w = await mountView(ProductsView)
    await w.find('.ibtn.ed').trigger('click')
    expect(w.find('#pr-name').element.value).toBe('SODA CÁUSTICA')
    await w.find('#pr-name').setValue('soda')
    await w.find('[data-act="save-product"]').trigger('click')
    await flushPromises()
    expect(api.called('PATCH', '/produtos/p-soda')[0].body).toMatchObject({ nome: 'SODA', versao: 7 })
    expect(db.products[0].versao).toBe(8)
    expect(lastToast()).toContain('atualizado')
  })
  it('409: toast com a mensagem do back e lista recarregada', async () => {
    api.on('GET /produtos', ok([product({ versao: 1 })]))
    const w = await mountView(ProductsView)
    api.on('PATCH /produtos/:id', err(409, 'O registro foi alterado por outro usuário.'))
    api.on('GET /produtos', ok([product({ nome: 'SODA NOVA', versao: 2 })]))
    await w.find('.ibtn.ed').trigger('click')
    await w.find('[data-act="save-product"]').trigger('click')
    await flushPromises()
    expect(toasts.at(-1).type).toBe('err')
    expect(lastToast()).toBe('O registro foi alterado por outro usuário.')
    expect(api.called('GET', '/produtos')).toHaveLength(2)
    expect(db.products[0].nome).toBe('SODA NOVA')
  })
  it('Excluir virou Inativar (confirmação) e depois Ativar', async () => {
    api.on('GET /produtos', ok([product()]))
    api.on('POST /produtos/:id/inativar', ok(product({ ativo: false })))
    api.on('POST /produtos/:id/ativar', ok(product({ ativo: true })))
    const w = await mountView(ProductsView)
    expect(w.find('.ibtn.dl').attributes('title')).toBe('Inativar')
    await w.find('.ibtn.dl').trigger('click')
    expect(modal).toMatchObject({ open: true, kind: 'confirm' })
    expect(modal.payload).toMatchObject({ title: 'Confirmar inativação', label: 'Inativar' })
    modal.payload.onYes()
    await flushPromises()
    expect(api.called('POST', '/produtos/p-soda/inativar')).toHaveLength(1)
    expect(w.find('tbody tr').classes()).toContain('off')
    expect(w.find('.ibtn.ok').attributes('title')).toBe('Ativar')
    await w.find('.ibtn.ok').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/produtos/p-soda/ativar')).toHaveLength(1)
    expect(w.find('tbody tr').classes()).not.toContain('off')
  })
  it('sem permissão de alterar não mostra ações', async () => {
    loginAs(createSession({ ...meSeller, permissoes: { ...meSeller.permissoes, PRODUTO: { ver: true, inserir: false, alterar: false, cancelar: false } } }))
    api.on('GET /produtos', ok([product()]))
    const w = await mountView(ProductsView)
    expect(w.find('[data-act="new-product"]').exists()).toBe(false)
    expect(w.find('.ibtn').exists()).toBe(false)
  })
})

describe('CarriersView', () => {
  const list = () => [carrier(), carrier({ id: 't-v', nome_fantasia: 'ROTA SUL', razao_social: 'ROTA SUL LTDA', cnpj: null, email: null, telefone: null, ativo: false })]

  it('lista sem usuário/senha; CNPJ mascarado e situação', async () => {
    api.on('GET /transportadoras', ok(list()))
    const w = await mountView(CarriersView)
    expect(w.findAll('thead th').map((t) => t.text())).toEqual(['Ações', 'Transportadora', 'Razão social', 'CNPJ', 'E-mail', 'Telefone', 'Situação'])
    const rows = w.findAll('tbody tr')
    expect(rows[0].text()).toContain('11.222.333/0001-81')
    expect(rows[0].text()).toContain('ATIVA')
    expect(rows[1].text()).toContain('INATIVA')
    expect(rows[1].classes()).toContain('off')
    expect(w.find('[data-pw]').exists()).toBe(false)
  })
  it('busca e filtros no cliente: texto, situação e revisar CNPJ', async () => {
    api.on('GET /transportadoras', ok([...list(), carrier({ id: 't-r', nome_fantasia: 'SEM CNPJ', cnpj: null, revisao_pendente: true })]))
    const w = await mountView(CarriersView)
    expect(w.findAll('tbody tr')).toHaveLength(3)
    await w.find('[data-flt="text"]').setValue('rota')
    expect(w.findAll('tbody tr')).toHaveLength(1)
    expect(w.find('.card-h .cnt').text()).toBe('1 de 3 cadastradas')
    await w.find('[data-flt="text"]').setValue('')
    await w.find('[data-flt="situacao"]').setValue('ATIVO')
    expect(w.findAll('tbody tr')).toHaveLength(2)
    await w.find('[data-flt="situacao"]').setValue('')
    await w.find('[data-flt="revisao"]').setValue('sim')
    expect(w.findAll('tbody tr')).toHaveLength(1)
    expect(w.find('tbody').text()).toContain('SEM CNPJ')
    await w.find('[data-flt="text"]').setValue('zzz')
    expect(w.find('tbody .empty').text()).toContain('para esse filtro')
  })
  it('incluir: POST com CNPJ só dígitos e aviso para criar usuários', async () => {
    api.on('GET /transportadoras', ok([]))
    api.on('POST /transportadoras', ({ body }) => ok(carrier({ id: 't-new', ...body }), {}, 201))
    const w = await mountView(CarriersView)
    await w.find('[data-act="new-carrier"]').trigger('click')
    expect(w.find('#cr-user').exists()).toBe(false)
    expect(w.find('#cr-pass').exists()).toBe(false)
    await w.find('#cr-fantasia').setValue('arco')
    await w.find('#cr-razao').setValue('ARCO Transportes Ltda')
    await w.find('#cr-cnpj').setValue('11222333000181')
    expect(w.find('#cr-cnpj').element.value).toBe('11.222.333/0001-81')
    await w.find('#cr-email').setValue('a@b.com')
    await w.find('[data-act="save-carrier"]').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/transportadoras')[0].body).toEqual({ razao_social: 'ARCO Transportes Ltda', nome_fantasia: 'ARCO', cnpj: '11222333000181', email: 'a@b.com', telefone: null, whatsapp_grupo_id: null })
    expect(lastToast()).toContain('Usuários e Acessos')
  })
  it('editar com versao; validação de obrigatórios', async () => {
    api.on('GET /transportadoras', ok([carrier({ versao: 3 })]))
    api.on('PATCH /transportadoras/:id', ({ body }) => ok(carrier({ ...body, versao: 4 })))
    const w = await mountView(CarriersView)
    await w.find('.ibtn.ed').trigger('click')
    expect(w.find('#cr-cnpj').element.value).toBe('11.222.333/0001-81')
    await w.find('#cr-razao').setValue('')
    await w.find('[data-act="save-carrier"]').trigger('click')
    await flushPromises()
    expect(toasts.at(-1).type).toBe('err')
    await w.find('#cr-razao').setValue('ARCO NOVA')
    await w.find('[data-act="save-carrier"]').trigger('click')
    await flushPromises()
    expect(api.called('PATCH', '/transportadoras/t-arco')[0].body.versao).toBe(3)
    expect(db.carriers[0].versao).toBe(4)
  })
  it('inativar com confirmação e ativar', async () => {
    api.on('GET /transportadoras', ok([carrier()]))
    api.on('POST /transportadoras/:id/inativar', ok(carrier({ ativo: false })))
    api.on('POST /transportadoras/:id/ativar', ok(carrier({ ativo: true })))
    const w = await mountView(CarriersView)
    await w.find('.ibtn.dl').trigger('click')
    expect(modal.payload.title).toBe('Confirmar inativação')
    modal.payload.onYes()
    await flushPromises()
    expect(db.carriers[0].ativo).toBe(false)
    await w.find('.ibtn.ok').trigger('click')
    await flushPromises()
    expect(db.carriers[0].ativo).toBe(true)
  })
  it('a confirmação renderiza no ModalHost com rótulo Inativar', async () => {
    api.on('GET /transportadoras', ok([carrier()]))
    const w = await mountView(CarriersView)
    await w.find('.ibtn.dl').trigger('click')
    const host = mount(ModalHost)
    expect(host.find('.modal-f .btn-danger').text()).toBe('Inativar')
    expect(host.find('.confirm-body').text()).toContain('ARCO')
  })
})

describe('UsersView (gestão de usuários)', () => {
  const groups = [
    { codigo: 'ADMINISTRADOR', nome: 'Administrador', tipo_usuario: 'INTERNO' },
    { codigo: 'VENDEDOR', nome: 'Vendedor', tipo_usuario: 'INTERNO' },
    { codigo: 'TRANSPORTADORA', nome: 'Transportadora', tipo_usuario: 'TRANSPORTADORA' },
  ]
  const users = () => [
    { id: 'u1', nome: 'Marcos', login: 'marcos', email: null, situacao: 'ATIVO', tipo_usuario: 'INTERNO', transportadora_id: null, grupos: ['VENDEDOR'], versao: 1 },
    { id: 'u2', nome: 'Operador ARCO', login: 'arco', email: null, situacao: 'BLOQUEADO', tipo_usuario: 'TRANSPORTADORA', transportadora_id: 't-arco', grupos: ['TRANSPORTADORA'], versao: 0 },
  ]
  beforeEach(() => {
    api.on('GET /usuarios', ok(users()))
    api.on('GET /grupos', ok(groups))
    api.on('GET /transportadoras', ok([carrier()]))
  })

  it('lista usuários com grupos (nome), transportadora e situação', async () => {
    const w = await mountView(UsersView)
    const rows = w.findAll('tbody tr')
    expect(rows).toHaveLength(2)
    expect(rows[0].text()).toContain('marcos')
    expect(rows[0].find('.pill.st-tra').text()).toBe('Vendedor')
    expect(rows[1].text()).toContain('ARCO')
    expect(rows[1].text()).toContain('BLOQUEADO')
    expect(rows[1].classes()).toContain('off')
  })
  it('criar usuário interno: grupos como chips, sem transportadora', async () => {
    api.on('POST /usuarios', ({ body }) => ok({ id: 'u3', situacao: 'ATIVO', tipo_usuario: 'INTERNO', versao: 0, ...body }, {}, 201))
    const w = await mountView(UsersView)
    await w.find('[data-act="new-user"]').trigger('click')
    expect(w.findAll('.chipz label').map((l) => l.text())).toEqual(['Administrador', 'Vendedor', 'Transportadora'])
    expect(w.find('#us-transp').exists()).toBe(false)
    await w.find('#us-nome').setValue('Lucia')
    await w.find('#us-login').setValue('LUCIA')
    await w.find('#us-senha').setValue('vendas1234')
    await w.findAll('.chipz input')[1].setValue(true)
    await w.find('[data-act="save-user"]').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/usuarios')[0].body).toEqual({ nome: 'Lucia', login: 'lucia', email: null, telefone: null, grupos: ['VENDEDOR'], transportadora_id: null, senha: 'vendas1234' })
    expect(w.findAll('tbody tr')).toHaveLength(3)
    expect(lastToast()).toContain('lucia')
  })
  it('grupo de transportadora exige vincular a transportadora', async () => {
    api.on('POST /usuarios', ({ body }) => ok({ id: 'u3', situacao: 'ATIVO', tipo_usuario: 'TRANSPORTADORA', versao: 0, ...body }, {}, 201))
    const w = await mountView(UsersView)
    await w.find('[data-act="new-user"]').trigger('click')
    await w.find('#us-nome').setValue('Zé')
    await w.find('#us-login').setValue('zeca')
    await w.find('#us-senha').setValue('senha1234')
    await w.findAll('.chipz input')[2].setValue(true)
    expect(w.find('#us-transp').exists()).toBe(true)
    await w.find('[data-act="save-user"]').trigger('click')
    await flushPromises()
    expect(toasts.at(-1).type).toBe('err')
    expect(api.called('POST', '/usuarios')).toHaveLength(0)
    await w.find('#us-transp').setValue('t-arco')
    await w.find('[data-act="save-user"]').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/usuarios')[0].body).toMatchObject({ grupos: ['TRANSPORTADORA'], transportadora_id: 't-arco' })
  })
  it('editar não exige senha e envia versao', async () => {
    api.on('PATCH /usuarios/:id', ({ body }) => ok({ id: 'u1', situacao: 'ATIVO', tipo_usuario: 'INTERNO', ...body, versao: 2 }))
    const w = await mountView(UsersView)
    await w.find('.ibtn.ed').trigger('click')
    expect(w.find('#us-nome').element.value).toBe('Marcos')
    expect(w.find('#us-senha').attributes('placeholder')).toContain('manter')
    await w.find('[data-act="save-user"]').trigger('click')
    await flushPromises()
    const body = api.called('PATCH', '/usuarios/u1')[0].body
    expect(body.versao).toBe(1)
    expect(body).not.toHaveProperty('senha')
  })
  it('bloquear com confirmação e reativar', async () => {
    api.on('POST /usuarios/:id/bloquear', ok({ ...users()[0], situacao: 'BLOQUEADO' }))
    api.on('POST /usuarios/:id/ativar', ({ params }) => ok({ ...users().find((u) => u.id === params.id), situacao: 'ATIVO' }))
    const w = await mountView(UsersView)
    await w.findAll('tbody tr')[0].find('.ibtn.dl').trigger('click')
    expect(modal.payload.label).toBe('Bloquear')
    modal.payload.onYes()
    await flushPromises()
    expect(w.findAll('tbody tr')[0].text()).toContain('BLOQUEADO')
    await w.findAll('tbody tr')[1].find('.ibtn.ok').trigger('click')
    await flushPromises()
    expect(api.called('POST', '/usuarios/u2/ativar')).toHaveLength(1)
    expect(w.findAll('tbody tr')[1].text()).toContain('ATIVO')
  })
})
